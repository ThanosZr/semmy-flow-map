function parse(raw: string) {
  const courses: Record<string, Course> = {};
  const cats = {} as Record<CatId, Category>;
  let cur: CatId | null = null;
  for (const rawLine of raw.trim().split('\n')) {
    const line = rawLine.trim();
    if (!line) continue;
    if (line.startsWith('#')) {
      const [id, name] = line.slice(1).split('|') as [CatId, string];
      cur = id;
      cats[id] = { id, name, ids: [] };
      continue;
    }
    if (!cur) throw new Error(`Course before category: ${line}`);
    const [code, name, flag] = line.split('|');
    const parts = code.split('.');
    const id = parts[parts.length - 2];
    if (courses[id]) throw new Error(`Duplicate course id ${id}`);
    courses[id] = { id, code, name, sem: Number(parts[parts.length - 1]), cat: cur, na: flag === '‡' };
    cats[cur].ids.push(id);
  }
  return { courses, cats };
}

const parsed = parse(RAW);
export const COURSES: Readonly<Record<string, Course>> = parsed.courses;
export const CATEGORIES: Readonly<Record<CatId, Category>> = parsed.cats;
